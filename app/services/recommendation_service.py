def competition_level_label(competitor_count):
    count = int(competitor_count or 0)
    if count == 0:
        return f"Very Low ({count} competitors)"
    if count <= 2:
        return f"Low ({count} competitors)"
    if count <= 6:
        return f"Moderate ({count} competitors)"
    return f"High ({count} competitors)"
