def _headline_and_type_for(cluster_label):
    if cluster_label == "Saturated":
        return ("HIGH SATURATION -- avoid this market or pivot to a clearly differentiated niche.",
                "High Saturation")
    if cluster_label == "High":
        return ("MODERATE-HIGH SATURATION -- consider a niche angle or a nearby underserved location.",
                "Moderate Opportunity")
    if cluster_label == "Moderate":
        return ("MODERATE OPPORTUNITY -- viable with a solid differentiation strategy.",
                "Moderate Opportunity")
    return ("HIGH OPPORTUNITY -- favorable conditions for market entry.", "High Opportunity")


def _kind_of_business(context):
    """"a bakery" when a sub-category is known, else "a food and beverage
    business" -- the summary should name what the owner actually said
    they are opening."""
    label = context.get("subcategory_label")
    if context.get("subcategory") and context.get("subcategory") != "other" and label:
        return label.lower()
    return f"{context['industry_type'].lower()} business"


def _number(value, default=None):
    """A payload figure as a plain float, or `default` when it is
    missing or not a number. The payload is the model agent's contract
    and is JSON-safe, but a row stored by an earlier build may lack a
    key, and the writers below must never raise over that."""
    if value is None or isinstance(value, bool):
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _figure(value, places=1):
    """A payload figure as prose quotes it: whole numbers without a
    decimal point, anything else to `places` decimals, with thousands
    separators. Quoting the payload's own rounding (rather than
    re-rounding to something prettier) is what lets the explanation
    pass the same grounding check the LLM's wording has to pass."""
    value = float(value or 0)
    if value.is_integer():
        return f"{value:,.0f}"
    return f"{value:,.{places}f}"


def _peso(value):
    """₱ amounts: whole pesos when the figure is whole or large,
    centavos only for small prices that actually have them."""
    value = float(value or 0)
    if value.is_integer() or abs(value) >= 1000:
        return f"₱{value:,.0f}"
    return f"₱{value:,.2f}"


def _plural(count, word):
    count = int(count or 0)
    return f"{count} {word}" + ("" if count == 1 else "s")


def _join(parts):
    """"a", "a and b", "a, b and c"."""
    parts = [p for p in parts if p]
    if len(parts) <= 1:
        return "".join(parts)
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def _forecast(context):
    """The trained model's payload from a context, or None."""
    forecast = context.get("forecast")
    return forecast if isinstance(forecast, dict) else None


def _plan_model_is_trained(forecast):
    """True when the plan stage was the trained forest; False for the
    scorecard-formula fallback used while no plan_model.pkl exists. The
    prose says which, rather than calling a formula a trained model."""
    plan = forecast.get("plan") or {}
    return str(plan.get("model_version") or "").startswith("plan_rf")


def _market_model_is_trained(forecast):
    """The same question for the market stage: True for the trained
    forest ("rf_v1"), False for forecasting_service's weighted-formula
    fallback ("formula_v1") used while no rf_model.pkl exists. Asked
    separately because the two stages can each be missing on their own
    -- a trained plan model sitting on a formula market reading is a
    real state, and the prose must not call that formula a model."""
    market = forecast.get("market") or {}
    return str(market.get("model_version") or "").startswith("rf")


def _capital_and_pricing_lines(context):
    """(reasons, risks) about the two things the plan model weighs that
    the market model never sees: whether the capital carries the plan
    through its ramp-up, and whether the price list can cover the fixed
    costs at a sales volume the barangay can plausibly support.

    Every figure quoted is the payload's own -- runway, ramp-up, fixed
    cost, required daily sales, daily sales ceiling -- so these lines
    can never disagree with the forecast they sit under. Empty when the
    context carries no plan forecast."""
    forecast = _forecast(context)
    if forecast is None:
        return [], []
    financials = forecast.get("financials") or {}
    inputs = forecast.get("inputs") or {}
    reasons, risks = [], []

    capital = _number(inputs.get("capital"), _capital(context))
    runway = _number(financials.get("capital_runway_months"), 0.0)
    ramp = _number(financials.get("ramp_up_months"))
    fixed_cost = _number(financials.get("monthly_fixed_cost"))
    if ramp is not None and fixed_cost is not None:
        if capital <= 0:
            risks.append(
                f"no capital is on file for this plan, so the forecast counts no runway against the "
                f"~{_figure(ramp)}-month ramp-up the model expects -- add your capital for an accurate forecast"
            )
        elif runway >= ramp:
            reasons.append(
                f"your capital of {_peso(capital)} covers about {_figure(runway)} months of fixed costs "
                f"({_peso(fixed_cost)}/month), longer than the ~{_figure(ramp)}-month ramp-up the model expects"
            )
        else:
            risks.append(
                f"your capital of {_peso(capital)} covers only about {_figure(runway)} months of fixed costs "
                f"({_peso(fixed_cost)}/month), shorter than the ~{_figure(ramp)}-month ramp-up the model "
                f"expects -- more capital, fewer staff at the start, or a cheaper site would close the gap"
            )

    priced = int(_number(inputs.get("priced_item_count"), 0) or 0)
    required = _number(financials.get("required_daily_sales"), 0.0)
    ceiling = _number(financials.get("daily_sales_ceiling"), 0.0)
    average = _number(inputs.get("average_price"), 0.0)
    if priced > 0 and required > 0:
        need = (f"at an average price of {_peso(average)} you need about {_figure(required)} sales a day "
                f"to cover fixed costs")
        if ceiling <= 0:
            risks.append(f"{need}, and no local demand ceiling could be estimated for {context['location']}")
        elif required <= ceiling / 2:
            reasons.append(f"{need} -- well within the ~{_figure(ceiling)} a day this barangay's residents "
                           f"could plausibly support")
        elif required <= ceiling:
            risks.append(f"{need} -- more than half of the ~{_figure(ceiling)} a day this barangay's residents "
                         f"could plausibly support, so there is little slack; higher-margin items or lower "
                         f"fixed costs would ease it")
        else:
            risks.append(f"{need} -- more than the ~{_figure(ceiling)} a day this barangay's residents could "
                         f"plausibly support; raise prices, add higher-value items or cut fixed costs")
    return reasons, risks


def _summary_for(context):
    forecast = _forecast(context)
    if forecast is not None:
        plan = forecast.get("plan") or {}
        viability = _number(plan.get("viability_score"), _number(context.get("viability_score"), 0.0))
        writer = "the trained plan model" if _plan_model_is_trained(forecast) else "the plan scorecard"
        summary = (
            f"A {_kind_of_business(context)} in {context['location']} is currently classified as "
            f"'{context['cluster_label']}' saturation ({round(context['saturation_index'])}%); once your "
            f"capital, staffing, pricing and offering are factored in, {writer} puts its viability at "
            f"{_figure(viability)}/10."
        )
    else:
        summary = (
            f"A {_kind_of_business(context)} in {context['location']} is currently classified as "
            f"'{context['cluster_label']}' saturation ({round(context['saturation_index'])}%), with a viability "
            f"score of {context['viability_score']}/10 for the parameters you entered."
        )
    analysis = context.get("subcategory_analysis")
    if analysis and analysis.get("adjusts_score"):
        summary += (
            f" Industry-wide the figure is {round(context['industry_saturation_index'])}%; it moves because "
            f"direct {analysis['label'].lower()} competition here is "
            f"{'lighter' if analysis['density_ratio'] < 1 else 'heavier'} than usual."
        )
    return summary


def _reasons_for(context):
    cluster_label = context["cluster_label"]
    industry_lower = context["industry_type"].lower()
    reasons = []
    if cluster_label in ("Low", "Moderate"):
        reasons.append(f"only {context['competitor_count']} existing {industry_lower} business(es) found "
                        f"in {context['location']}")
        if context["population"]:
            reasons.append(f"a real population of {context['population']:,} gives room for a new entrant")
        else:
            reasons.append("demand indicators suggest room for a new entrant")
    else:
        reasons.append(f"{context['competitor_count']} existing {industry_lower} business(es) already "
                        f"serve {context['location']}")
    analysis = context.get("subcategory_analysis")
    if analysis and not analysis.get("is_estimated") and analysis.get("density_ratio", 1) < 1:
        reasons.append(
            f"only {analysis['direct_count']} direct {analysis['label'].lower()} competitor(s) measured in "
            f"{context['location']} -- fewer than its {analysis['industry_count']} "
            f"{industry_lower} businesses would normally hold"
        )
    if _forecast(context) is not None:
        # The plan model weighed the capital against the ramp-up, so
        # say what it found rather than only that a figure exists.
        reasons.extend(_capital_and_pricing_lines(context)[0])
    elif _capital(context):
        reasons.append(f"your capital of PHP {_capital(context):,.0f} is on file for this plan")
    reasons.append(f"model confidence for this estimate is {round(context['confidence_level'])}%")
    return reasons


def _risks_for(context):
    cluster_label = context["cluster_label"]
    risks = []
    if cluster_label in ("High", "Saturated"):
        risks.append(f"the market is already {round(context['saturation_index'])}% saturated in "
                      f"{context['location']}")
        risks.append("expect strong price/brand competition from existing businesses")
    else:
        risks.append("initial brand-awareness building will still be required")
        risks.append("monitor seasonal demand fluctuations after launch")
    analysis = context.get("subcategory_analysis")
    if analysis:
        if analysis.get("is_estimated"):
            risks.append(
                f"the direct {analysis['label'].lower()} competitor count (~{analysis['direct_count']}) is an "
                f"estimate -- no sub-category count is on file for {context['location']} yet, so the score "
                f"is the industry-wide one"
            )
        elif analysis.get("density_ratio", 1) > 1:
            risks.append(
                f"{analysis['direct_count']} direct {analysis['label'].lower()} competitor(s) in "
                f"{context['location']} -- denser than usual for its {analysis['industry_count']} "
                f"{context['industry_type'].lower()} businesses"
            )
    risks.extend(_capital_and_pricing_lines(context)[1])
    if context["competitor_simulated"]:
        risks.append("competitor count for this area is a simulated estimate -- connect a live Google "
                      "Places API key for exact figures")
    return risks


# How much a new entrant has to stand out, by the saturation tier the
# model put this plan in. Read from the model's own output -- the only
# market fact the rule-based writer has -- not from the idea's wording,
# which it cannot judge. Judging the idea itself is the LLM's job.
_DIFFERENTIATION_NEED = {
    "Saturated": "Very high",
    "High": "High",
    "Moderate": "Moderate",
    "Low": "Low",
}

_DIFFERENTIATION_SUGGESTIONS = {
    "Very high": [
        "make the difference visible before anyone buys -- signage, packaging or a sample customers can try",
        "test the idea with a small batch or a weekend stall before committing the full capital",
        "pick one thing to be known for rather than competing on everything the established shops offer",
    ],
    "High": [
        "lead with the difference in your name, signage and first posts, so it is what people remember",
        "price the new item so trying it is an easy yes next to what regulars already buy",
        "ask your first customers what made them choose you, and double down on that",
    ],
    "Moderate": [
        "the market has room, so the idea is a head start rather than a lifeline -- consistency matters as much",
        "keep the idea simple enough to deliver the same way every day",
    ],
    "Low": [
        "competition is light, so reliability and convenience can matter more than novelty at first",
        "keep the idea as a way to hold customers once competitors arrive",
    ],
}


def _rule_based_innovation(context):
    """What the plan's differentiation is up against. The rule-based
    writer does NOT rate how new the idea is -- it has no way to know --
    so `novelty` stays None here and only the LLM fills it in."""
    need = _DIFFERENTIATION_NEED.get(context["cluster_label"], "Moderate")
    analysis = context.get("subcategory_analysis")
    if analysis:
        rivals = f"{'about ' if analysis.get('is_estimated') else ''}{analysis['direct_count']} direct " \
                 f"{analysis['label'].lower()} competitor(s)"
    else:
        rivals = f"{context['competitor_count']} {context['industry_type'].lower()} business(es)"

    idea = (context.get("innovation_idea") or "").strip()
    if idea:
        summary = (
            f"Your idea goes up against {rivals} in {context['location']}, where the market is "
            f"{round(context['saturation_index'])}% saturated -- differentiation need: {need.lower()}."
        )
    else:
        summary = (
            f"You have not said what makes the business different yet. With {rivals} in "
            f"{context['location']}, differentiation need is {need.lower()} -- add your idea to the plan "
            f"for a clearer read."
        )

    prices = context.get("price_summary")
    if prices and prices.get("priced"):
        if prices["low"] == prices["high"]:
            summary += f" Your price list has {prices['count']} item(s) at PHP {prices['low']:,.2f}."
        else:
            summary += (f" Your price list has {prices['count']} item(s), from PHP {prices['low']:,.2f} "
                        f"to PHP {prices['high']:,.2f}.")

    return {
        "has_idea": bool(idea),
        "differentiation_need": need,
        "novelty": None,
        "summary": summary,
        "suggestions": list(_DIFFERENTIATION_SUGGESTIONS.get(need, [])),
        "generated_by": "rule_based",
    }


# ---------------------------------------------------------------------
# 2a. The competitor insight -- "how many of you are already here, and
#     can this plan still win?"
# ---------------------------------------------------------------------
# The Planning page shows it SHORT (one or two sentences next to the
# direct-competitor count) and the Recommendations page shows it IN FULL,
# so the two pages say the same thing at two lengths rather than two
# different things.
#
# The AI writes both (llm_service asks for "competitor_insight"), because
# the judgement it needs -- is THIS pandesal idea new against the
# pandesal shops already trading here? -- is a reading of words, which a
# template cannot do. This rule-based version is what stands when the AI
# is off or its text quotes a figure it was not given; it says only what
# the numbers say, and names the novelty only when the AI rated it.
#
# Built from STORED fields alone (the sub-category analysis, the market
# payload, the innovation read), so parse_recommendation() can give a
# forecast written before this existed the same insight.

def competitor_insight_from(analysis, competitor_count, industry_type, location, innovation):
    """{"short", "detail", "generated_by", "label", "direct_count",
    "industry_count", "is_estimated", "source"} -- the rule-based insight."""
    innovation = innovation or {}
    has_idea = bool(innovation.get("has_idea"))
    novelty = innovation.get("novelty")
    need = (innovation.get("differentiation_need") or "Moderate").lower()
    industry_count = int(_number(competitor_count, 0) or 0)
    location = location or "this barangay"

    if analysis:
        label = str(analysis.get("label") or "Direct competitor")
        direct = int(_number(analysis.get("direct_count"), 0) or 0)
        estimated = bool(analysis.get("is_estimated"))
        kind = label.lower()
        ratio = _number(analysis.get("density_ratio"), 1.0) or 1.0
        if estimated:
            crowd = ("No count of this exact kind of business is on file for this barangay yet, "
                     "so that number is an estimate.")
        elif ratio < 1:
            crowd = ("That is fewer than a barangay with this many businesses usually has, so direct "
                     "competition is lighter than the industry figure suggests.")
        elif ratio > 1:
            crowd = ("That is more than a barangay with this many businesses usually has, so direct "
                     "competition is heavier than the industry figure suggests.")
        else:
            crowd = "That is about what is usual for a barangay with this many businesses."
    else:
        label = industry_type or "Competitor"
        direct = industry_count
        estimated = False
        kind = (industry_type or "business").lower()
        crowd = "Pick a sub-category on the plan to count only the businesses that sell what you sell."
    count_text = f"{'About ' if estimated else ''}{direct} {kind} business{'es' if direct != 1 else ''}"

    if novelty == "High":
        chance_short = "Your idea reads as genuinely new here, so the plan has a real chance."
        chance = ("Your idea reads as genuinely new here, so even with that competition the plan has a "
                  "real chance, provided customers can see the difference from day one.")
    elif novelty == "Moderate":
        chance_short = "Your idea is partly new here and can set you apart."
        chance = ("Your idea is partly new here: it can set you apart, but expect competitors to copy what "
                  "works, so make it the thing you are known for.")
    elif novelty == "Low":
        chance_short = "Your idea looks close to what is already offered, so sharpen the difference."
        chance = ("Your idea looks close to what is already offered here, so it will not set you apart on "
                  "its own; sharpen the difference before you open.")
    elif has_idea:
        chance_short = f"Your idea is what has to set you apart (differentiation need: {need})."
        chance = (f"You have described what makes you different; with a differentiation need of {need}, "
                  "that idea is what has to carry the plan against them.")
    else:
        chance_short = f"Add what makes you different for a clearer read (differentiation need: {need})."
        chance = (f"You have not said what makes you different yet, and the differentiation need here is "
                  f"{need}. Add your idea to the plan for a clearer read.")

    return {
        "short": f"{count_text} already trade in {location}. {chance_short}",
        "detail": f"{count_text} already trade in {location}. {crowd} {chance}",
        "generated_by": RULE_BASED_EXPLANATION,
        "label": label,
        "direct_count": direct,
        "industry_count": industry_count,
        "is_estimated": estimated,
        "source": (analysis or {}).get("source"),
    }


