def _parse_competitor_insight(payload):
    """The stored insight, or -- for a forecast written before insights
    existed -- the rule-based one rebuilt from what that row DID store,
    so the Planning and Recommendations pages never show a gap."""
    value = payload.get("competitor_insight")
    if isinstance(value, dict) and value.get("short"):
        return value
    forecast = payload.get("forecast") if isinstance(payload.get("forecast"), dict) else {}
    market = forecast.get("market") or {}
    inputs = forecast.get("inputs") or {}
    analysis = payload.get("subcategory_analysis")
    analysis = analysis if isinstance(analysis, dict) else None
    if not analysis and not market:
        return None
    innovation = payload.get("innovation")
    return competitor_insight_from(
        analysis, market.get("competitor_count"), inputs.get("industry_type"),
        inputs.get("location"), innovation if isinstance(innovation, dict) else None,
    )


def _parse_explanation(value):
    """{"text", "generated_by"} from storage -- plus "transcript_failed_at"
    when an upgrade to a Gemini transcript last failed (see
    mark_transcript_failed) -- or None when the row has no usable
    transcript (every row written before the two-stage model)."""
    if not isinstance(value, dict):
        return None
    text = str(value.get("text") or "").strip()
    if not text:
        return None
    parsed = {"text": text, "generated_by": str(value.get("generated_by") or RULE_BASED_EXPLANATION)}
    if isinstance(value.get("transcript_failed_at"), str):
        parsed["transcript_failed_at"] = value["transcript_failed_at"]
        parsed["transcript_failed_version"] = value.get("transcript_failed_version")
    return parsed


# ---------------------------------------------------------------------
# 3b. Upgrading a STORED forecast's transcript
# ---------------------------------------------------------------------
# A forecast stored with the rule-based model summary -- made while no
# Gemini key was configured, or before the transcript existed -- is
# upgraded after the fact, from the page, without blocking its render:
# the page shows the summary with a "Gemini is transcribing..." note,
# and static/js/forecast_transcript.js asks
# POST /api/forecasts/<id>/transcript (api_controller). Nothing is
# re-scored: the context is rebuilt from the stored payload and the
# plan, and only the stored "explanation" changes.

def _utc(stamp):
    """An ISO timestamp as an aware UTC datetime, or None. A naive one is
    read as UTC (that is how every timestamp here is written)."""
    try:
        when = datetime.fromisoformat(str(stamp).strip().replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None
    return when if when.tzinfo else when.replace(tzinfo=timezone.utc)


def transcript_failed_recently(explanation, now=None):
    """True while a failed upgrade is younger than TRANSCRIPT_RETRY_AFTER
    AND was made with the current Gemini request -- a stamp left by an
    older request version is ignored (see TRANSCRIPT_REQUEST_VERSION)."""
    if not isinstance(explanation, dict):
        return False
    if explanation.get("transcript_failed_version") != TRANSCRIPT_REQUEST_VERSION:
        return False
    when = _utc(explanation.get("transcript_failed_at"))
    if when is None:
        return False
    now = now or datetime.now(timezone.utc)
    return now - when < TRANSCRIPT_RETRY_AFTER


def transcript_upgrade_due(rec, now=None):
    """Whether the page should ask Gemini to write what is still the
    template in this parsed recommendation (parse_recommendation's
    dict): it carries the model's payload, its recommendation or its
    transcript is still rule-based (ai_text_pending), no upgrade failed
    in the last TRANSCRIPT_RETRY_AFTER, and Gemini can plausibly be
    asked (llm_service.gemini_transcription_available -- the LLM switch
    on and a usable Gemini key). Registered as the template global
    `forecast_transcript_due` (api_controller), read by
    shared/_plan_insights.html. The cheap checks come first, so a page
    of AI-written forecasts never touches the key or the switch."""
    if not ai_text_pending(rec):
        return False
    explanation = rec.get("explanation")
    if not isinstance(explanation, dict) or not explanation.get("text"):
        return False
    if transcript_failed_recently(explanation, now):
        return False
    from app.services.llm_service import gemini_transcription_available

    return gemini_transcription_available()


def transcript_queue_due(rec, now=None):
    """Whether a plan's LATEST forecast should be queued for a Gemini
    transcript in the background (Planning and Home queue every plan,
    not only the one on screen). Either its transcript can be upgraded
    (transcript_upgrade_due), or it predates the plan model altogether
    -- no payload to transcribe -- and the endpoint re-runs the plan's
    forecast, which writes a transcript as it goes."""
    if transcript_upgrade_due(rec, now):
        return True
    if not isinstance(rec, dict) or isinstance(rec.get("forecast"), dict):
        return False
    from app.services.llm_service import gemini_transcription_available

    return gemini_transcription_available()


def stored_recommendation(raw_text):
    """forecast_result.recommendation as the dict it was stored as, or
    None for a legacy plain-text row or anything unreadable."""
    try:
        payload = json.loads(str(raw_text or ""))
    except (ValueError, TypeError):
        return None
    return payload if isinstance(payload, dict) else None


def store_transcript(raw_text, transcript):
    """The stored recommendation JSON with ONLY its "explanation"
    replaced by `transcript` ({"text", "generated_by"}). Every other key
    -- the payload, the headline, the reasons, anything a later version
    added -- is written back exactly as it was read; the retry stamp of
    an earlier failure goes with the summary it was attached to."""
    payload = stored_recommendation(raw_text)
    if payload is None:
        raise ValueError("not a stored JSON recommendation")
    payload["explanation"] = {"text": transcript["text"], "generated_by": transcript["generated_by"]}
    return json.dumps(payload, ensure_ascii=False)


def mark_transcript_failed(raw_text, now=None):
    """The stored recommendation JSON with explanation["transcript_failed_at"]
    set to now (ISO, UTC), so the page leaves this forecast alone for
    TRANSCRIPT_RETRY_AFTER. The model summary's text and everything else
    stay as they were."""
    payload = stored_recommendation(raw_text)
    if payload is None:
        raise ValueError("not a stored JSON recommendation")
    explanation = dict(payload.get("explanation") or {}) if isinstance(payload.get("explanation"), dict) else {}
    payload["explanation"] = _stamped(explanation, now)
    return json.dumps(payload, ensure_ascii=False)


def transcript_retry_in(explanation, now=None):
    """Whole seconds until a failed upgrade may be retried (0 when it may
    be now) -- what the page waits before asking again."""
    when = _utc((explanation or {}).get("transcript_failed_at")) if isinstance(explanation, dict) else None
    if when is None or not transcript_failed_recently(explanation, now):
        return 0
    now = now or datetime.now(timezone.utc)
    return max(1, int((when + TRANSCRIPT_RETRY_AFTER - now).total_seconds()) + 1)


def transcript_context(forecast_row, sme_profile):
    """The context transcribe_forecast needs, rebuilt for a STORED
    forecast -- from its stored payload and its plan, with no scoring.
    The market figures come from the payload (what the forecast actually
    said), the row's own columns standing in only where an older payload
    lacks one. None when the row has no payload to transcribe."""
    stored = parse_recommendation(forecast_row.recommendation)
    payload = stored.get("forecast")
    if not isinstance(payload, dict):
        return None
    market = payload.get("market") or {}
    plan = payload.get("plan") or {}
    inputs = payload.get("inputs") or {}
    saturation = _number(market.get("saturation_index"), _number(forecast_row.saturation_index, 0.0))
    scores = {
        "saturation_index": saturation,
        "industry_saturation_index": _number(market.get("industry_saturation_index"), saturation),
        "cluster_label": market.get("cluster_label") or forecast_row.cluster_label,
        "viability_score": _number(plan.get("viability_score"), _number(forecast_row.viability_score, 0.0)),
        "confidence_level": _number(forecast_row.confidence_level,
                                    _number(plan.get("confidence"), _number(market.get("confidence"), 0.0))),
        "competitor_count": int(_number(market.get("competitor_count"), 0) or 0),
    }
    return build_recommendation_context(
        sme_profile, scores,
        population=_number(inputs.get("population"), 0) or 0,
        subcategory_analysis=stored.get("subcategory_analysis"),
        plan_forecast=payload,
    )


def _opportunity_type_from_headline(headline):
    upper = (headline or "").upper()
    if "HIGH SATURATION" in upper:
        return "High Saturation"
    if "MODERATE" in upper:
        return "Moderate Opportunity"
    if "HIGH OPPORTUNITY" in upper:
        return "High Opportunity"
    return "Moderate Opportunity"


def parse_recommendation(raw_text):
    """Returns the structured dict every template expects, whether
    `raw_text` is one of THIS version's JSON-serialized
    recommendations, or a legacy plain-text row written by the old
    rule_based_text()/LLM plain-text generator this module used before
    this change (format: "<HEADLINE>\\n\\n<summary>\\n\\nWhy: r1; r2.
    \\n\\nConsiderations: c1; c2."). Never raises -- a value nobody can
    make sense of still returns a fully-shaped dict so every template
    field always has *something* to render."""
    if not raw_text or not str(raw_text).strip():
        return _empty_recommendation()

    text = str(raw_text).strip()

    if text.startswith("{"):
        try:
            payload = json.loads(text)
        except (ValueError, TypeError):
            payload = None
        if isinstance(payload, dict) and "headline" in payload:
            return {
                "headline": payload.get("headline") or "",
                "opportunity_type": payload.get("opportunity_type") or "Moderate Opportunity",
                "summary": payload.get("summary") or "",
                "reasons": [str(r) for r in (payload.get("reasons") or [])],
                "risks": [str(r) for r in (payload.get("risks") or [])],
                "generated_by": payload.get("generated_by") or "rule_based",
                # Absent on forecasts written before sub-categories and
                # the innovation read existed; templates check for None.
                "subcategory_analysis": payload.get("subcategory_analysis")
                if isinstance(payload.get("subcategory_analysis"), dict) else None,
                "innovation": payload.get("innovation")
                if isinstance(payload.get("innovation"), dict) else None,
                # Absent on forecasts written before the trained plan
                # model; the Home page regenerates those once.
                "forecast": payload.get("forecast")
                if isinstance(payload.get("forecast"), dict) else None,
                "explanation": _parse_explanation(payload.get("explanation")),
                "competitor_insight": _parse_competitor_insight(payload),
            }

    # Legacy plain-text fallback (pre-JSON format).
    headline = text.split("\n", 1)[0].strip()

    summary_match = re.search(r"\n\n(.*?)\n\nWhy:", text, re.DOTALL)
    summary = re.sub(r"\s+", " ", summary_match.group(1)).strip() if summary_match else ""

    why_match = re.search(r"Why:\s*(.*?)\.?\s*(?:\n\n|$)", text, re.DOTALL)
    reasons = [r.strip() for r in why_match.group(1).split(";") if r.strip()] if why_match else []

    considerations_match = re.search(r"Considerations:\s*(.*?)\.?\s*$", text, re.DOTALL)
    risks = [r.strip() for r in considerations_match.group(1).split(";") if r.strip()] if considerations_match else []

    return {
        "headline": headline,
        "opportunity_type": _opportunity_type_from_headline(headline),
        "summary": summary,
        "reasons": reasons,
        "risks": risks,
        "generated_by": "legacy",
        "subcategory_analysis": None,
        "innovation": None,
        "forecast": None,
        "explanation": None,
        "competitor_insight": None,
    }


